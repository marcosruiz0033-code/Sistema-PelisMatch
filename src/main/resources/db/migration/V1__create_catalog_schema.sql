CREATE TABLE categoria (
    id_categoria INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descripcion VARCHAR(200) NOT NULL,
    nombre VARCHAR(60) NOT NULL UNIQUE
);

CREATE TABLE peliculas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anio INTEGER NOT NULL,
    descripcion VARCHAR(255),
    director VARCHAR(255),
    duracion INTEGER,
    genero VARCHAR(255),
    imagen VARCHAR(500),
    puntuacion DOUBLE PRECISION,
    reparto VARCHAR(2000),
    sinopsis VARCHAR(2000),
    titulo VARCHAR(150) NOT NULL,
    url_apple_tv VARCHAR(500),
    url_disney_plus VARCHAR(500),
    url_max VARCHAR(500),
    url_netflix VARCHAR(500),
    url_prime_video VARCHAR(500),
    url_trailer VARCHAR(500),
    id_categoria INTEGER,
    CONSTRAINT fk_peliculas_categoria
        FOREIGN KEY (id_categoria) REFERENCES categoria (id_categoria)
);

CREATE TABLE serie (
    id_serie INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anio INTEGER NOT NULL,
    estado VARCHAR(30) NOT NULL,
    imagen VARCHAR(500),
    temporadas INTEGER,
    sinopsis VARCHAR(2000),
    titulo VARCHAR(150) NOT NULL,
    url_apple_tv VARCHAR(500),
    url_disney_plus VARCHAR(500),
    url_max VARCHAR(500),
    url_netflix VARCHAR(500),
    url_prime_video VARCHAR(500),
    url_trailer VARCHAR(500),
    id_categoria INTEGER,
    CONSTRAINT fk_serie_categoria
        FOREIGN KEY (id_categoria) REFERENCES categoria (id_categoria)
);

CREATE TABLE usuario (
    id_usuario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    correo VARCHAR(100) NOT NULL UNIQUE,
    nombre VARCHAR(60) NOT NULL,
    password VARCHAR(255) NOT NULL,
    rol VARCHAR(255) NOT NULL
);

CREATE TABLE favorito (
    id_favorito INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario INTEGER NOT NULL,
    id_pelicula BIGINT,
    id_serie INTEGER,
    CONSTRAINT fk_favorito_usuario
        FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario),
    CONSTRAINT fk_favorito_pelicula
        FOREIGN KEY (id_pelicula) REFERENCES peliculas (id),
    CONSTRAINT fk_favorito_serie
        FOREIGN KEY (id_serie) REFERENCES serie (id_serie)
);

CREATE TABLE serie_capitulo (
    id_capitulo INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descripcion VARCHAR(1000) NOT NULL,
    numero_capitulo INTEGER NOT NULL,
    temporada INTEGER NOT NULL,
    titulo VARCHAR(150),
    id_serie INTEGER NOT NULL,
    CONSTRAINT fk_serie_capitulo_serie
        FOREIGN KEY (id_serie) REFERENCES serie (id_serie)
);
